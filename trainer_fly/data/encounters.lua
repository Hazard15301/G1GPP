function Data.resolve(index, pokemonByIndex)
  index = tonumber(index)
  if not index then
    return { kind = "invalid", index = index }
  end

  local glitch = Data.glitchPokemon[index]
  if glitch then
    return {
      kind = "pokemon",
      subtype = "glitch",
      index = index,
      species = glitch.id,
      definition = glitch,
    }
  end

  local species = pokemonByIndex and pokemonByIndex[index]
  if species then
    return {
      kind = "pokemon",
      subtype = "normal",
      index = index,
      species = species,
    }
  end

  local crash = Data.crashEffects[index]
  if crash then
    return {
      kind = "crash_effect",
      index = index,
      effect = crash,
    }
  end

  if index >= 191 and index <= 255 then
    return {
      kind = "upper_pending",
      index = index,
    }
  end

  return {
    kind = "unsupported",
    index = index,
  }
end

